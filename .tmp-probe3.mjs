import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1200, height: 700 } })
const p = await ctx.newPage()
p.on('console', (m) => console.log('PAGE:', m.text()))
p.on('pageerror', (e) => console.log('PAGE ERROR:', e.message))
await p.goto('http://localhost:4199/', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(500)
// instrument: does an observer see the cards at all?
await p.evaluate(() => {
  const el = document.querySelector('h4')
  const io = new IntersectionObserver((es) => console.log('probe IO:', es[0].isIntersecting), {})
  io.observe(el)
})
await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
await p.waitForTimeout(1500)
console.log('after scroll (1.5s):', await p.evaluate(() => document.querySelector('h4').getAttribute('style')))
await p.waitForTimeout(2500)
console.log('after fallback (4s):', await p.evaluate(() => document.querySelector('h4').getAttribute('style')))
await b.close()
